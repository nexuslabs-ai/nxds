const FILL = '-fill';

/** The `@phosphor-icons/react` component for an icon name: `PlusIcon` for `plus` and `plus-fill`. */
export function iconComponent(name: string) {
  return `${(name.endsWith(FILL) ? name.slice(0, -FILL.length) : name)
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')}Icon`;
}

/** The weight an icon name draws: `fill` for a `-fill` name. */
export function iconWeight(name: string) {
  return name.endsWith(FILL) ? 'fill' : undefined;
}
