/** The `@tabler/icons-react` component for an icon name: `IconPlus` for `plus`. */
export function iconComponent(name: string) {
  return `Icon${name
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')}`;
}
